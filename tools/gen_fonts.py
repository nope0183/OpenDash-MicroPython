#!/usr/bin/env python3
"""Convert the GFX fonts from the original OpenDash ``src/ru_fonts.h``
into a compact Python module for the MicroPython port.

Usage:
    python tools/gen_fonts.py path/to/OpenDash/src/ru_fonts.h

The generated file is ``opendash/fonts.py``.  The original fonts are
1-bit Arial-derived GFX fonts with Latin and Cyrillic coverage; only the
characters used by the port are kept.
"""
import os
import re
import sys

DEFAULT_HEADER = os.path.join("..", "OpenDash", "src", "ru_fonts.h")

# ASCII + Cyrillic + the few punctuation marks used by the UI.
CHARSET = list(range(0x20, 0x7F)) + [
    0x00B0, 0x00AB, 0x00BB,
    0x0401,
] + list(range(0x0410, 0x0450)) + [
    0x0451,
    0x2013, 0x2014, 0x2026, 0x2116, 0x2212,
]


def parse_font(text, name):
    mf = re.search(
        r"static const GFXfont " + name +
        r" PROGMEM = \{\(uint8_t\s*\*\)" + name +
        r"_bmp,\s*\(GFXglyph\s*\*\)" + name +
        r"_glyph,\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(\d+)\};",
        text)
    mb = re.search(
        r"static const uint8_t " + name + r"_bmp\[\] PROGMEM = \{(.*?)\};",
        text, re.S)
    mg = re.search(
        r"static const GFXglyph " + name + r"_glyph\[\] PROGMEM = \{(.*?)\};",
        text, re.S)
    if not (mf and mb and mg):
        raise ValueError("cannot parse font " + name)
    first = int(mf.group(1), 16)
    last = int(mf.group(2), 16)
    y_advance = int(mf.group(3))
    bitmap = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", mb.group(1)))
    glyphs = {}
    rows = re.findall(r"\{([^}]*)\}", mg.group(1))
    if len(rows) != last - first + 1:
        raise ValueError("glyph count mismatch for " + name)
    for code in CHARSET:
        if code < first or code > last:
            continue
        row = [int(v.strip()) for v in rows[code - first].split(",")]
        if len(row) != 6:
            raise ValueError("bad glyph row")
        off, w, h, xadv, xoff, yoff = row
        # Keep zero-size glyphs such as space: their x_advance still matters.
        if (w == 0 or h == 0) and xadv == 0:
            continue
        glyphs[code] = (off, w, h, xadv, xoff, yoff)
    # A fallback glyph: '?'
    if ord("?") not in glyphs and ord("?") >= first:
        row = [int(v.strip()) for v in rows[ord("?") - first].split(",")]
        glyphs[ord("?")] = tuple(row)
    ascent = max(-yoff for (_, _, _, _, _, yoff) in glyphs.values())
    descent = max(yoff + h for (_, _, h, _, _, yoff) in glyphs.values())
    return bitmap, glyphs, y_advance, ascent, max(0, descent)


def main():
    header = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_HEADER
    text = open(header, encoding="utf-8").read()
    out = [
        "# Generated by tools/gen_fonts.py from OpenDash src/ru_fonts.h.",
        "# Do not edit manually.",
        "",
        "# font id -> (bitmap, glyphs, y_advance, ascent, descent)",
        "# glyph = (bitmap_offset, width, height, x_advance, x_offset, y_offset)",
        "FONTS = {",
    ]
    for font_id, name in ((1, "RU1"), (2, "RU2"), (4, "RU4")):
        bitmap, glyphs, y_adv, ascent, descent = parse_font(text, name)
        out.append("    %d: (%r, {" % (font_id, bitmap))
        for code in sorted(glyphs):
            out.append("        %d: %r," % (code, glyphs[code]))
        out.append("    }, %d, %d, %d)," % (y_adv, ascent, descent))
    out.append("}")
    out.append("")
    dst = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "opendash", "fonts.py")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", dst)


if __name__ == "__main__":
    main()
